import Foundation

public typealias DocumentRenderer = ReferenceRenderer

public struct ReferenceRenderer: Sendable {
  public static let minContentLength = 100

  public static func renderFromJSON(_ jsonData: AppleDocJSON, sourceURL: String) -> String {
    var markdown = ""

    markdown += generateFrontMatter(jsonData, sourceURL: sourceURL)

    let breadcrumbs = generateBreadcrumbs(sourceURL)
    if !breadcrumbs.isEmpty {
      markdown += breadcrumbs
    }

    if let roleHeading = jsonData.metadata?.roleHeading {
      markdown += "**\(roleHeading)**\n\n"
    }

    if let title = jsonData.metadata?.title, !title.isEmpty {
      markdown += "# \(title)\n\n"
    }

    if let platforms = jsonData.metadata?.platforms, !platforms.isEmpty {
      markdown += "**Available on:** \(ContentRenderer.formatPlatforms(platforms))\n\n"
    }

    markdown += ContentRenderer.renderAbstractQuote(
      jsonData.abstract, references: jsonData.references)

    markdown += ContentRenderer.renderLanguageNotice(jsonData)
    markdown += renderDeprecationNotice(jsonData, references: jsonData.references)

    if let primarySections = jsonData.primaryContentSections {
      let declarationSection = primarySections.first { $0.kind == "declarations" }
      if let declarations = declarationSection?.declarations {
        markdown += renderDeclarations(declarations)
      }

      let parametersSection = primarySections.first { $0.kind == "parameters" }
      if let parameters = parametersSection?.parameters {
        markdown += renderParameters(parameters, references: jsonData.references)
      }

      let propertiesSection = primarySections.first { $0.kind == "properties" }
      if let properties = propertiesSection?.items {
        markdown += ContentRenderer.renderProperties(properties, references: jsonData.references)
      }

      let possibleValuesSection = primarySections.first { $0.kind == "possibleValues" }
      if let values = possibleValuesSection?.values {
        markdown += ContentRenderer.renderPossibleValues(values, references: jsonData.references)
      }

      let contentSections = primarySections.filter { $0.kind == "content" }
      for section in contentSections {
        if let content = section.content {
          markdown += renderContentArray(content, references: jsonData.references)
        }
      }
    }

    if let relationships = jsonData.relationshipsSections {
      markdown += renderRelationships(
        relationships, variants: jsonData.variants, refs: jsonData.references)
    }

    if let topics = jsonData.topicSections {
      markdown += ContentRenderer.renderTopicSections(
        topics, variants: jsonData.variants, refs: jsonData.references)
    }

    if let seeAlso = jsonData.seeAlsoSections {
      markdown += ContentRenderer.renderSeeAlso(
        seeAlso, variants: jsonData.variants, refs: jsonData.references)
    }

    markdown = markdown.trimmingCharacters(in: .whitespacesAndNewlines)

    markdown += "\n\n---\n\n"
    markdown +=
      "*Generated by [swift-developer-docs-mcp](https://github.com/mehmetbaykar/swift-developer-docs-mcp) - Making Apple docs AI-readable.*\n"
    markdown += "*This is unofficial content. All documentation belongs to Apple Inc.*\n"

    return markdown
  }

  // MARK: - Private Helpers

  static func generateFrontMatter(_ data: AppleDocJSON, sourceURL: String) -> String {
    var lines: [String] = []

    if let title = data.metadata?.title {
      let cleanTitle = title.replacingOccurrences(of: "| Apple Developer Documentation", with: "")
        .trimmingCharacters(in: .whitespaces)
      lines.append("title: \(cleanTitle)")
    }

    if let abstract = data.abstract {
      let description = ContentRenderer.renderPlainText(abstract, references: data.references)
        .trimmingCharacters(in: .whitespacesAndNewlines)
      if !description.isEmpty {
        lines.append("description: \(description)")
      }
    }

    lines.append("source: \(sourceURL)")

    let formatter = ISO8601DateFormatter()
    formatter.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
    lines.append("timestamp: \(formatter.string(from: Date()))")

    if isSymbolDeprecated(data) {
      lines.append("deprecated: true")
    }

    return "---\n\(lines.joined(separator: "\n"))\n---\n\n"
  }

  static func generateBreadcrumbs(_ sourceURL: String) -> String {
    guard let url = URL(string: sourceURL) else { return "" }
    let pathParts = url.pathComponents.filter { $0 != "/" }

    if pathParts.count < 3 { return "" }

    let framework = pathParts[1]
    let capitalizedFramework = framework.prefix(1).uppercased() + framework.dropFirst()
    var breadcrumbs = "**Navigation:** [\(capitalizedFramework)](/documentation/\(framework))"

    if pathParts.count > 3 {
      for i in 2..<(pathParts.count - 1) {
        let part = pathParts[i]
        let path = pathParts[0...i].joined(separator: "/")
        breadcrumbs += " › [\(part)](/\(path))"
      }
    }

    return "\(breadcrumbs)\n\n"
  }

  static func renderDeclarations(_ declarations: [Declaration]) -> String {
    var markdown = ""
    for decl in declarations {
      guard let tokens = decl.tokens else { continue }
      let code =
        tokens
        .compactMap { $0.text }
        .joined()
        .trimmingCharacters(in: .whitespacesAndNewlines)
      if !code.isEmpty {
        let fence = decl.languages?.contains("occ") == true ? "objc" : "swift"
        markdown += "```\(fence)\n\(code)\n```\n\n"
      }
    }
    return markdown
  }

  static func renderDeprecationNotice(
    _ data: AppleDocJSON, references: [String: ContentItem]?, externalOrigin: String? = nil
  ) -> String {
    guard
      let body = deprecationNoticeBody(
        data, references: references, externalOrigin: externalOrigin)
    else { return "" }
    return MarkdownFormatting.formatCallout(type: "WARNING", content: body, lead: "**Deprecated**")
  }

  static func isSymbolDeprecated(_ data: AppleDocJSON) -> Bool {
    deprecationNoticeBody(data, references: data.references) != nil
  }

  private static func deprecationNoticeBody(
    _ data: AppleDocJSON, references: [String: ContentItem]?, externalOrigin: String? = nil
  ) -> String? {
    if let summary = data.deprecationSummary, !summary.isEmpty {
      let rendered = ContentRenderer.renderContentArray(
        summary, references: references, externalOrigin: externalOrigin
      ).trimmingCharacters(in: .whitespacesAndNewlines)
      if !rendered.isEmpty { return rendered }
    }

    if let platformMessage = deprecationMessage(from: data.metadata?.platforms) {
      return platformMessage
    }

    if let identifier = data.identifier?.url, references?[identifier]?.deprecated == true {
      return "This symbol is deprecated."
    }

    return nil
  }

  private static func deprecationMessage(from platforms: [Platform]?) -> String? {
    guard let platforms, !platforms.isEmpty else { return nil }
    let deprecatedPlatforms = platforms.filter { $0.deprecated == true || $0.deprecatedAt != nil }
    guard !deprecatedPlatforms.isEmpty else { return nil }

    var uniqueMessages: [String] = []
    for platform in deprecatedPlatforms {
      guard let message = platform.message?.trimmingCharacters(in: .whitespacesAndNewlines),
        !message.isEmpty
      else { continue }
      if !uniqueMessages.contains(message) {
        uniqueMessages.append(message)
      }
    }

    if uniqueMessages.count == 1 {
      return uniqueMessages[0]
    }

    if uniqueMessages.count > 1 {
      return deprecatedPlatforms.compactMap { platform in
        guard let message = platform.message?.trimmingCharacters(in: .whitespacesAndNewlines),
          !message.isEmpty
        else { return nil }
        return "**\(platform.name):** \(message)"
      }.joined(separator: "\n")
    }

    return "This symbol is deprecated."
  }

  static func renderParameters(_ params: [Parameter], references: [String: ContentItem]?) -> String
  {
    if params.isEmpty { return "" }
    var markdown = "## Parameters\n\n"
    for param in params {
      markdown += "**\(param.name)**\n\n"
      if let content = param.content {
        let paramText = ContentRenderer.renderContentArray(
          content, references: references, depth: 0)
        markdown += "\(paramText)\n\n"
      }
    }
    return markdown
  }

  // MARK: - Delegating to ContentRenderer

  static func renderContentArray(
    _ content: [ContentItem], references: [String: ContentItem]?, depth: Int = 0
  ) -> String {
    ContentRenderer.renderContentArray(content, references: references, depth: depth)
  }

  static func renderInlineContent(
    _ inlineContent: [ContentItem], references: [String: ContentItem]?, depth: Int = 0
  ) -> String {
    ContentRenderer.renderInlineContent(inlineContent, references: references, depth: depth)
  }

  static func convertIdentifierToURL(_ identifier: String, references: [String: ContentItem]?)
    -> String
  {
    ContentRenderer.convertIdentifierToURL(identifier, references: references)
  }

  static func extractTitleFromIdentifier(_ identifier: String) -> String {
    ContentRenderer.extractTitleFromIdentifier(identifier)
  }

  static func mapAsideStyleToCallout(_ style: String) -> String {
    ContentRenderer.mapAsideStyleToCallout(style)
  }

  // MARK: - Relationships

  static func renderRelationships(
    _ rels: [ContentItem], variants: [Variant]?, refs: [String: ContentItem]?
  ) -> String {
    ContentRenderer.renderRelationships(rels, variants: variants, refs: refs)
  }

}
